// Imports Armageddon 2070's WIR networks from Yumon Pet:
//   cd ../yumon-pet/wir && cargo run --release -- armageddon --out examples/armageddon --export ../tmp/wir-armageddon/armageddon.json
//   node tools/ar_import_wir.mjs ../../../yumon-pet/tmp/wir-armageddon/armageddon.json
// Writes src/games/armageddon/ar_wir_data.ts: the sense stencil and every brain as sparse layers
// with input/output names and constants (sources stay in yumon-pet/wir/examples/armageddon).
import fs from "node:fs";
const src = process.argv[2];
if (!src) { console.error("usage: node tools/ar_import_wir.mjs armageddon.json"); process.exit(1); }
const d = JSON.parse(fs.readFileSync(src, "utf8"));
if (d.format !== "wir-armageddon") throw new Error(`not a wir armageddon export: ${d.format}`);
const int = (v) => (Number.isInteger(v) ? v : Number(v.toPrecision(12)));
const layers = (ls) => ls.map((l) => ({ b: l.b.map(int), rows: l.rows.map((r) => r.map(int)) }));
const nets = Object.fromEntries(Object.entries(d.nets).map(([name, n]) => [name, { kind: n.kind, variant: n.variant, consts: n.consts, inputs: n.inputs, ranges: n.ranges, outputs: n.outputs, layers: layers(n.layers) }]));
const out = { consts: d.consts, sense: { channels: d.sense.channels, taps: d.sense.taps, pads: d.sense.pads, outputs: d.sense.outputs, layers: layers(d.sense.layers) }, nets };
const text = `// GENERATED by tools/ar_import_wir.mjs from Yumon Pet's \`wir armageddon --export\` (do not edit).
// Armageddon 2070's WIR networks: the shared 5 x 5 senses and every brain (infantry roles, squad,
// strategic, tanks, transports, helicopters, jets, mecha), compiled from the WIR programs in
// yumon-pet/wir/examples/armageddon and checked exact against them (docs/ARMAGEDDON_2070.md).
import type { ArWirData } from "./ar_wir";
export const AR_WIR: ArWirData = ${JSON.stringify(out)};
`;
fs.writeFileSync(new URL("../src/games/armageddon/ar_wir_data.ts", import.meta.url), text);
console.log(`wrote ar_wir_data.ts (${text.length.toLocaleString()} bytes; ${Object.keys(nets).length} brains + sense)`);
