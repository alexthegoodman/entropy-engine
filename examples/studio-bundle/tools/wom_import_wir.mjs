// Imports the WIR tactical networks for World of Music's enemies from Yumon Pet:
//   cd ../yumon-pet/wir && cargo run --release -- tactics --out examples --export ../tmp/wir-tactics/tactics_demo.json
//   node tools/wom_import_wir.mjs ../../../yumon-pet/tmp/wir-tactics/tactics_demo.json
// Writes src/games/world_of_music/wom_wir_data.ts: the path step and sense stencils and the
// "full" brain set (grunt, rusher, sniper) as sparse layers, without the WIR sources.
import fs from "node:fs";
const src = process.argv[2];
if (!src) { console.error("usage: node tools/wom_import_wir.mjs tactics_demo.json"); process.exit(1); }
const d = JSON.parse(fs.readFileSync(src, "utf8"));
if (d.format !== "wir-tactics-demo") throw new Error(`not a wir tactics export: ${d.format}`);
const int = (v) => (Number.isInteger(v) ? v : Number(v.toPrecision(12)));
const layers = (ls) => ls.map((l) => ({ b: l.b.map(int), rows: l.rows.map((r) => r.map(int)) }));
const stencil = (s) => ({ taps: s.taps, pads: s.pads, layers: layers(s.layers) });
const brains = d.brains.full.map(({ source, layers: ls, hidden, params, inputs, outputs, ...rest }) => ({ ...rest, layers: layers(ls) }));
const out = {
    consts: d.consts,
    path: stencil(d.path),
    sense: stencil(d.sense),
    brains,
};
const text = `// GENERATED by tools/wom_import_wir.mjs from Yumon Pet's \`wir tactics --export\` (do not edit).
// The WIR tactical networks World of Music's enemies think with: an 8-move path step, the
// 5 x 5 senses, and the grunt / rusher / sniper brains, compiled from WIR programs and checked
// exact against their rules in yumon-pet/wir (docs/WIR.md "Tactical enemies").
import type { WirData } from "./wom_wir";
export const WIR_DATA: WirData = ${JSON.stringify(out)};
`;
fs.writeFileSync(new URL("../src/games/world_of_music/wom_wir_data.ts", import.meta.url), text);
console.log(`wrote wom_wir_data.ts (${text.length.toLocaleString()} bytes; ${brains.map((b) => b.name).join(", ")})`);
